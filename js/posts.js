/* 工具函数：按日期倒序 */
function sortedPosts() {
  return [...POSTS].sort((a, b) => (a.date < b.date ? 1 : -1));
}

/* 工具函数：收集所有标签（带计数） */
function allTags() {
  const map = {};
  POSTS.forEach((p) =>
    p.tags.forEach((t) => (map[t] = (map[t] || 0) + 1))
  );
  return Object.entries(map).sort((a, b) => b[1] - a[1]);
}
